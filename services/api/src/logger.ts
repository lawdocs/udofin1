import { type LoggerOptions } from 'pino';
import { type AppConfig } from './config.js';

/** Credential headers, redacted on requests and responses. */
const REDACTED_HEADERS = ['authorization', 'cookie', 'set-cookie', 'x-api-key'] as const;

/**
 * Field names that must never reach logs, at any depth we log. Identity numbers, OTPs, contact
 * details, bank details and credentials are redacted even if a developer logs a whole object.
 * Prefer not logging payloads at all; this list is the safety net, not the policy.
 */
export const REDACTED_KEYS = [
  'password',
  'secret',
  'token',
  'accessToken',
  'refreshToken',
  'otp',
  'pin',
  'aadhaar',
  'aadhaarNumber',
  'vid',
  'pan',
  'panNumber',
  'ckycNumber',
  'phone',
  'mobile',
  'mobileNumber',
  'email',
  'dob',
  'dateOfBirth',
  'accountNumber',
  'bankAccountNumber',
  'upiId',
  'vpa',
  'address',
  'fullName',
] as const;

/** Lower-case alphanumerics only, so `phone_number`, `PhoneNumber` and `PHONE-NUMBER` all match. */
function normalise(key: string): string {
  return key.toLowerCase().replace(/[^a-z0-9]/g, '');
}

const REDACTED_NORMALISED = new Set<string>([
  ...REDACTED_KEYS.map(normalise),
  // Common spellings that are not simple case variants of the list above.
  'name',
  'phonenumber',
  'mobileno',
  'panno',
  'aadhar',
  'aadhaarno',
  'accountno',
  'acctno',
  'ifsc',
  'authorization',
  'apikey',
  'credential',
  'credentials',
  'passwd',
  'sessiontoken',
  'idtoken',
  'jwt',
  'cvv',
  'cardnumber',
]);

const MAX_DEPTH = 10;

/** Recursively replaces the value of any sensitive key, at any depth, in any spelling. */
export function deepRedact(value: unknown, depth = 0, seen = new WeakSet<object>()): unknown {
  if (value === null || typeof value !== 'object') return value;
  if (depth >= MAX_DEPTH) return '[TRUNCATED]';
  if (seen.has(value)) return '[CIRCULAR]';
  seen.add(value);
  if (Array.isArray(value)) return value.map((item) => deepRedact(item, depth + 1, seen));
  const out: Record<string, unknown> = {};
  for (const [key, inner] of Object.entries(value)) {
    out[key] = REDACTED_NORMALISED.has(normalise(key))
      ? '[REDACTED]'
      : deepRedact(inner, depth + 1, seen);
  }
  return out;
}

/**
 * Errors are logged by type and code, never by message or stack: database and provider errors
 * routinely embed the offending value (for example `Key (phone)=(...)`). Client errors (4xx) are
 * generated by our own validation and keep their message.
 */
interface ErrorLike {
  name?: string;
  code?: unknown;
  statusCode?: unknown;
  message?: unknown;
}
function serializeError(err: unknown): Record<string, unknown> {
  const e = (err ?? {}) as ErrorLike;
  const status = typeof e.statusCode === 'number' ? e.statusCode : undefined;
  return {
    type: typeof e.name === 'string' ? e.name : 'Error',
    ...(typeof e.code === 'string' ? { code: e.code } : {}),
    ...(status !== undefined ? { statusCode: status } : {}),
    ...(status !== undefined && status < 500 && typeof e.message === 'string'
      ? { message: e.message.slice(0, 200) }
      : {}),
  };
}

interface RequestLike {
  id?: unknown;
  method?: unknown;
  url?: unknown;
  ip?: unknown;
}
/** Requests are logged by method and path only: query strings often carry tokens or identifiers. */
function serializeRequest(req: unknown): Record<string, unknown> {
  const r = (req ?? {}) as RequestLike;
  const url = typeof r.url === 'string' ? (r.url.split('?')[0] ?? '') : '';
  return {
    id: r.id,
    method: r.method,
    path: url.slice(0, 200),
    remoteAddress: r.ip,
  };
}

export function redactPaths(): string[] {
  const paths: string[] = [];
  for (const header of REDACTED_HEADERS) {
    paths.push(
      `req.headers["${header}"]`,
      `res.headers["${header}"]`,
      `headers["${header}"]`,
      `*.headers["${header}"]`,
    );
  }
  return paths;
}

export function loggerOptions(config: Pick<AppConfig, 'LOG_LEVEL' | 'APP_ENV'>): LoggerOptions {
  return {
    level: config.LOG_LEVEL,
    base: { service: 'udofin-api', env: config.APP_ENV },
    timestamp: () => `,"time":"${new Date().toISOString()}"`,
    redact: { paths: redactPaths(), censor: '[REDACTED]' },
    serializers: { err: serializeError, req: serializeRequest },
    formatters: {
      level: (label) => ({ level: label }),
      log: (object) => deepRedact(object) as Record<string, unknown>,
    },
  };
}
